def system_language() -> str:
    """The language Windows itself is set to, as a two-letter code."""
    try:
        langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        code = _WINDOWS_PRIMARY.get(langid & 0x3FF)
        if code:
            return code
    except Exception:
        # Not Windows, or the call is unavailable: fall through to the locale.
        pass
    tag = (locale.getdefaultlocale()[0] or "en")[:2].lower()
    return tag if tag in _TEXT else "en"


LANGUAGE = system_language()


def tr(key: str, **values: object) -> str:
    """The phrase for `key` in the system language, English if it is missing."""
    text = _TEXT.get(LANGUAGE, _TEXT["en"]).get(key) or _TEXT["en"].get(key, key)
    return text.format(**values) if values else text
